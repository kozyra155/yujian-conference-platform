const {chromium}=require('D:/playwright-demo/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base='http://192.168.2.36:12880';
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN'});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.url().includes('/portal-assets/')&&response.status()>=400)errors.push(response.status()+' '+response.url());});
  try{
    assert.equal((await page.goto(base+'/register/')).status(),200);
    assert.equal(await page.getByRole('heading',{name:'创建遇见科技账号',exact:true}).count(),1);
    assert.match(await page.title(),/注册.*遇见科技/);
    assert.match(await page.locator('.meet-register-logo').getAttribute('src'),/meet-logo.png$/);
    assert.equal(await page.locator('#meet-register-email-form input[name="csrf_token"]').count(),1);
    assert.equal(await page.locator('#meet-register-email-form input[name="captcha"]').count(),1);
    const smtp=JSON.parse(fs.readFileSync(__dirname+'/smtp-settings.json','utf8').replace(/^\uFEFF/,''));
    assert.equal(await page.locator('#register-mail-notice').isVisible(),smtp.enabled!==true);
    const csrf=await page.locator('input[name="csrf_token"]').inputValue();
    const rejected=await page.request.post(base+'/register/',{form:{csrf_token:csrf,is_email_verification:'',email:'not-an-email',captcha:'invalid'}});
    assert.equal(rejected.status(),200);
    const html=await rejected.text();
    assert.match(html,/not-an-email/);
    assert.match(html,/invalid|无效|有效|格式|错误/i,'服务器保留无效邮箱校验');
    assert.ok(!html.includes('data-email-sent="true"'));
    assert.equal((await page.request.post(base+'/register/',{form:{email:'register-ui-test@yujian.example'}})).status(),400,'无 CSRF 的提交必须拒绝');
    await page.screenshot({path:__dirname+'/../output/yujian-register-desktop.png',fullPage:true});
    for(const width of [320,390,760,1024,1440]){
      await page.setViewportSize({width,height:844});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${width}px 注册页不能横向溢出`);
      if(width===390)await page.screenshot({path:__dirname+'/../output/yujian-register-mobile.png',fullPage:true});
    }
    await page.getByRole('link',{name:'立即登录',exact:true}).click();
    assert.equal(new URL(page.url()).pathname,'/login/');
    const preview=JSON.parse(fs.readFileSync(__dirname+'/.register-preview.json','utf8'));
    await page.goto(preview.url);
    await page.locator('#signup-container input[name="first_name"]').waitFor();
    assert.equal(await page.getByRole('heading',{name:'完善账户信息',exact:true}).count(),1);
    assert.match(await page.locator('.meet-register-steps li[aria-current="step"]').innerText(),/^2\s*填写账户信息$/);
    assert.equal(await page.locator('#signup-container input[name="email"]').getAttribute('readonly'),'');
    await page.locator('#signup-container input[name="password"]').fill('fixture-only-password');
    await page.locator('#signup-container input[name="password_confirm"]').fill('different-fixture-password');
    await page.locator('#signup-container input[name="password_confirm"]').press('Tab');
    await page.locator('#signup-container .error.field input[name="password_confirm"]').waitFor({state:'visible'});
    await page.locator('#signup-container input[name="password_confirm"]').fill('fixture-only-password');
    await page.locator('#signup-container input[name="password_confirm"]').press('Tab');
    await page.locator('#signup-container .error.field input[name="password_confirm"]').waitFor({state:'hidden'});
    assert.equal(await page.getByRole('button',{name:'完成注册',exact:true}).count(),1);
    await page.locator('#signup-container input[name="first_name"]').fill('语言切换草稿');
    await page.locator('.language-toggle').click();
    await page.waitForFunction(async()=>(await(await fetch('/assets/js-vars/user.js?portal=1')).json()).language==='en_GB');
    assert.equal(await page.locator('#signup-container input[name="first_name"]').inputValue(),'语言切换草稿');
    assert.equal(await page.locator('#signup-container input[name="password"]').inputValue(),'fixture-only-password');
    await page.locator('.language-toggle').click();
    await page.waitForFunction(async()=>(await(await fetch('/assets/js-vars/user.js?portal=1')).json()).language==='zh_Hans_CN');
    assert.equal(await page.locator('#signup-container input[name="first_name"]').inputValue(),'语言切换草稿');
    await page.screenshot({path:__dirname+'/../output/yujian-register-profile-desktop.png',fullPage:true});
    await page.mouse.move(0,0);
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'第二步手机布局不能溢出');
    await page.screenshot({path:__dirname+'/../output/yujian-register-profile-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    const result={passed:true,branding:true,csrf_rejected_without_token:true,captcha_preserved:true,invalid_email_rejected:true,mail_notice_matches_backend:true,login_link:true,profile_step:true,password_mismatch_rejected:true,real_email_delivery_tested:false,responsive_widths:[320,390,760,1024,1440],browser_errors:errors};
    fs.writeFileSync(__dirname+'/register-verification.json',JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
