const projectRoot=require('node:path').resolve(__dirname,'../..');
const {chromium}=require('D:/playwright-demo/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base='http://192.168.2.36:12880';
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN'});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.goto(base);
    assert.equal(await page.locator('.language-toggle').count(),1,'顶栏应提供可用的中英切换');
    await page.locator('.login-link').waitFor({state:'visible'});
    assert.equal(await page.locator('.account-menu').isVisible(),false);
    await page.locator('.language-toggle').click();
    assert.match(await page.locator('#hero-title').innerText(),/Meet Technology/);
    assert.equal(await page.locator('#main-nav').getByRole('link',{name:'Features',exact:true}).count(),1);
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    assert.match(await page.title(),/Meet Technology/);
    await page.goto(base+'/events/');
    assert.equal(await page.locator('#events-language').inputValue(),'en');
    await page.locator('.event-card').first().waitFor();
    const conferences=await(await page.request.get(base+'/api/conferences/?page=1&q=')).json();
    assert.equal(await page.locator('.event-title').first().innerText(),conferences.events[0].title);
    await page.locator('#events-language').selectOption('zh');
    await page.goto(base);
    assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN');
    const account=JSON.parse(fs.readFileSync(projectRoot+'/demo-accounts.json','utf8')).find(a=>a.username==='host-a');
    await page.goto(base+'/login/');
    await page.locator('input[name="identifier"]').fill(account.username);
    await page.locator('input[name="password"]').fill(account.password);
    await Promise.all([page.waitForURL(url=>!url.pathname.startsWith('/login/')),page.locator('#login-form').evaluate(f=>f.requestSubmit())]);
    await page.goto(base);
    await page.locator('.account-menu').waitFor({state:'visible'});
    assert.equal(await page.locator('.login-link').isVisible(),false,'已登录不能仍显示登录');
    const sessionResponse=await page.request.get(base+'/assets/js-vars/user.js?portal=1');
    const session=await sessionResponse.json();
    assert.ok(session.user.id);
    assert.ok(session.user.name);
    assert.equal(session.user.email,undefined,'门户会话只返回必要信息');
    assert.match(sessionResponse.headers()['cache-control'],/no-store/);
    assert.equal(await page.locator('.account-name').innerText(),session.user.name);
    await page.locator('.account-toggle').click();
    assert.equal(await page.getByRole('link',{name:'我的会议',exact:true}).count(),1);
    assert.equal((await page.request.get(base+'/user/dashboard/')).status(),200);
    assert.equal((await page.request.get(base+'/user/profile/')).status(),200);
    await page.locator('.language-toggle').click();
    await page.locator('.account-toggle').click();
    assert.equal(await page.getByRole('link',{name:'My conferences',exact:true}).count(),1);
    await page.waitForFunction(async()=>{const data=await(await fetch('/assets/js-vars/user.js?portal=1',{cache:'no-store'})).json();return data.language==='en_GB';});
    assert.match(await (await page.request.get(base+'/assets/js-vars/user.js')).text(),/Indico\.User\s*=/,'保留后台原生用户脚本');
    await page.screenshot({path:projectRoot+'/../output/yujian-home-signed-in-en.png',fullPage:true});
    await page.goto(base+'/events/');
    await page.locator('.account-menu').waitFor({state:'visible'});
    assert.equal(await page.locator('#events-language').inputValue(),'en');
    const anonymous=await browser.newPage({locale:'zh-CN'});
    await anonymous.goto(base);
    await anonymous.locator('.login-link').waitFor({state:'visible'});
    assert.equal(await anonymous.locator('.account-menu').isVisible(),false,'不同会话不得显示他人账户');
    await anonymous.close();
    await page.locator('.account-toggle').click();
    await page.locator('.account-logout').click();
    await page.locator('.login-link').waitFor({state:'visible'});
    assert.equal(await page.locator('.account-menu').isVisible(),false);
    await page.goto(base+'/register/');
    assert.equal(await page.getByRole('heading',{name:'Create your Meet Technology account',exact:true}).count(),1);
    await page.goto(base+'/login/');
    assert.equal(await page.locator('input[name="identifier"]').getAttribute('placeholder'),'Username or email');
    for(const width of [320,390,760,1024,1440]){
      await page.setViewportSize({width,height:844});
      for(const route of ['/','/events/']){await page.goto(base+route);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${route} English ${width}px overflow`);}
    }
    await page.route('**/assets/js-vars/user.js?portal=1',route=>route.fulfill({status:503,body:'Unavailable'}));
    await page.goto(base);
    await page.locator('.login-link').waitFor({state:'visible'});
    assert.equal(await page.locator('.account-menu').isVisible(),false);
    assert.equal(await page.locator('.login-link').innerText(),'Account');
    assert.equal(await page.locator('.account-name').innerText(),'');
    assert.deepEqual(errors,[]);
    const result={passed:true,real_session:true,no_identity_leak:true,logout:true,english:true,language_persisted:true,event_language_synced:true,auth_language:true,mobile:true,browser_errors:errors};
    fs.writeFileSync(projectRoot+'/session-language-verification.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
