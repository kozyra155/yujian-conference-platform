const projectRoot=require('node:path').resolve(__dirname,'../..');
const { chromium } = require('D:/playwright-demo/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = 'http://192.168.2.36:12880';
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => {if(response.url().startsWith(base+'/portal-assets/') && response.status() >= 400) errors.push(response.status()+' '+response.url());});
  try {
    assert.equal((await page.goto(base)).status(),200);
    assert.match(await page.title(),/遇见科技会议服务平台/,'首页应展示遇见科技品牌');
    await page.getByRole('button',{name:'下一张介绍'}).click();
    assert.match(await page.locator('#hero-title').innerText(),/专属会议网站/);
    await page.getByRole('button',{name:'第 1 张介绍'}).click();
    await page.getByText('遇见科技会议服务平台本地演示说明',{exact:true}).click();
    assert.equal(await page.locator('.news-list details').first().getAttribute('open'),'');
    const publicCount=(await(await page.request.get(base+'/api/conferences/')).json()).events.length;
    await page.waitForFunction(count=>document.querySelectorAll('.conference-row').length===count,publicCount);
    assert.equal(await page.locator('.conference-row').count(),publicCount);
    await page.getByRole('searchbox',{name:'会议名称或地点'}).fill('燃烧');
    await Promise.all([page.waitForResponse(r=>r.url().includes('/api/conferences/?')&&r.url().includes('q=')),page.getByRole('button',{name:'查询会议',exact:true}).click()]);
    await page.waitForFunction(()=>document.querySelectorAll('.conference-row').length===1);
    assert.equal(await page.locator('.conference-row:visible').count(),1);
    assert.match(await page.locator('.conference-row:visible').innerText(),/能源与燃烧/);
    await page.getByRole('searchbox',{name:'会议名称或地点'}).fill('长沙');
    await Promise.all([page.waitForResponse(r=>r.url().includes('/api/conferences/?')&&r.url().includes('q=')),page.getByRole('button',{name:'查询会议',exact:true}).click()]);
    await page.waitForFunction(()=>document.querySelectorAll('.conference-row').length===1);
    assert.equal(await page.locator('.conference-row:visible').count(),1);
    assert.match(await page.locator('.conference-row:visible').innerText(),/能源与燃烧/);
    await page.getByRole('searchbox',{name:'会议名称或地点'}).fill('没有这个会议');
    await Promise.all([page.waitForResponse(r=>r.url().includes('/api/conferences/?')&&r.url().includes('q=')),page.getByRole('button',{name:'查询会议',exact:true}).click()]);
    await page.locator('#no-results').waitFor({state:'visible'});
    assert.equal(await page.locator('.conference-row:visible').count(),0);
    assert.equal(await page.locator('#no-results').isVisible(),true);
    await page.getByRole('searchbox',{name:'会议名称或地点'}).fill('');
    await Promise.all([page.waitForResponse(r=>r.url().includes('/api/conferences/?')&&r.url().includes('q=')),page.getByRole('button',{name:'查询会议',exact:true}).click()]);
    await page.waitForFunction(count=>document.querySelectorAll('.conference-row').length===count,publicCount);
    assert.equal(await page.locator('.conference-row:visible').count(),publicCount);
    await page.goto(base);
    await page.screenshot({path:projectRoot+'/../output/yujian-home-desktop.png',fullPage:true});
    const createHref = await page.locator('.header-create').getAttribute('href');
    assert.ok(createHref && createHref !== '#');
    const createResponse = await page.goto(base+createHref);
    assert.ok(createResponse.status() < 400,'创建入口应可访问');
    assert.match(await page.locator('body').innerText(),/登录|创建|会议/);
    const accounts = JSON.parse(fs.readFileSync(projectRoot+'/demo-accounts.json','utf8'));
    const account = accounts.find(item=>item.username === 'host-a');
    const host = await browser.newPage({locale:'zh-CN'});
    await host.goto(base+'/login/');
    await host.locator('input[name="identifier"]').fill(account.username);
    await host.locator('input[name="password"]').fill(account.password);
    await Promise.all([host.waitForURL(url=>!url.pathname.startsWith('/login/')),host.locator('#login-form').evaluate(form=>form.requestSubmit())]);
    await host.goto(base+createHref);
    await host.locator('#builder-form').waitFor({state:'visible'});
    await host.locator('#builder-form input[name=title]').fill('前端入口验证（未提交）');
    assert.equal(await host.locator('#builder-form button[type=submit]').isEnabled(),true);
    await host.screenshot({path:projectRoot+'/../output/yujian-create-entry.png',fullPage:true});
    await host.close();
    assert.equal((await page.goto(base+'/event/1/')).status(),200);
    assert.match(await page.locator('body').innerText(),/人工智能/);
    assert.equal((await page.goto(base+'/event/2/')).status(),200);
    assert.match(await page.locator('body').innerText(),/能源与燃烧/);
    await page.setViewportSize({width:390,height:844});
    await page.goto(base);
    await page.getByRole('button',{name:'打开导航'}).click();
    assert.equal(await page.getByRole('navigation',{name:'主导航'}).isVisible(),true);
    await page.getByRole('navigation',{name:'主导航'}).getByRole('link',{name:'会议查询'}).click();
    assert.equal(await page.getByRole('button',{name:'打开导航'}).getAttribute('aria-expanded'),'false');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false,'手机不能横向溢出');
    for (const width of [320,760,1024,1920]) {
      await page.setViewportSize({width,height:900});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false,`${width}px 不能横向溢出`);
    }
    await page.setViewportSize({width:390,height:844});
    await page.goto(base);
    await page.screenshot({path:projectRoot+'/../output/yujian-home-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    const result={passed:true,desktop:1440,mobile:390,overflow_widths:[320,390,760,1024,1440,1920],search:true,empty_results:true,mobile_navigation:true,hero_controls:true,announcements:true,create_form_after_login:true,conference_details:true,browser_errors:errors};
    fs.writeFileSync(projectRoot+'/portal-verification.json',JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
